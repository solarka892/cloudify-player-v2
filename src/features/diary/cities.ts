export const CITIES: readonly DiaryCity[] = LIST.map(([name, lat, lon]) => ({ name, lat, lon }));

/** The cities whose name holds `query`, in any case; all of them for an empty one. */
export function citiesMatching(query: string): readonly DiaryCity[] {
  const words = query.trim().toLowerCase().replaceAll("ё", "е");
  if (!words) return CITIES;
  return CITIES.filter((city) => city.name.toLowerCase().replaceAll("ё", "е").includes(words));
}

